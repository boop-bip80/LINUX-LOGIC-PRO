#!/usr/bin/env python3
"""Independent synthetic integration of all P001 producer/consumer reports.

The source functions are deliberately tiny fixtures, not runtime evidence.
Actual tooling is copied from the supplied immutable implementation checkout.
The original review assembled the same bytes from separate owner worktrees;
published-code-review.json proves every Python file is identical.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


CODE_NAMES = ('inventory.py', 'run_baseline.py', 'prepare_sources.py', 'recover_baseline.py', 'verify_classifications.py')
TEST_NAMES = ('test_inventory.py', 'test_baseline_gate.py', 'test_prepare_sources.py', 'test_recovery.py', 'test_classifications.py')
STAGES = {
    'host_launch': [('.', 'src/startup/darling.c')],
    'mldr_mapping_and_dyld_handoff': [('.', 'src/startup/mldr/loader.c'), ('.', 'src/startup/mldr/mldr.c')],
    'dyld_dependency_loading': [('src/external/dyld', 'src/dyld2.cpp'), ('src/external/dyld', 'src/ImageLoader.cpp')],
    'system_library_initialization': [('src/external/libsystem', 'init.c')],
    'server_checkin_and_rpc_dispatch': [('src/external/darlingserver', 'src/call.cpp'), ('src/external/darlingserver', 'src/darlingserver.cpp')],
    'framework_initialization': [('src/external/objc4', 'runtime/objc-os.mm'), ('src/external/corefoundation', 'CFRuntime.c')],
}
CATEGORIES = [
    'native_linux_host', 'macho_runtime_component', 'implemented_body_unqualified',
    'partial_framework', 'developer_link_stub', 'generated_stub_tooling',
    'generated_style_stub_body', 'architecture_constraint',
]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path)
    parser.add_argument('--implementation-root', type=Path, required=True)
    args = parser.parse_args()
    implementation = args.implementation_root.resolve()
    code = {name: implementation / 'tools/compat/logic-pro' / name for name in CODE_NAMES}
    tests = {name: implementation / 'tests/compat/logic-pro/baseline' / name for name in TEST_NAMES}
    work = args.output or Path(tempfile.mkdtemp(prefix='p001-independent-strict-'))
    work.mkdir(parents=True, exist_ok=True)
    repo, sources = work / 'repo', work / 'sources'
    sources.mkdir()
    env = {k: v for k, v in os.environ.items() if not k.startswith('GIT_')}
    env.update({'GIT_CONFIG_NOSYSTEM': '1', 'GIT_CONFIG_GLOBAL': os.devnull,
                'GIT_AUTHOR_NAME': 'Independent P001 fixture', 'GIT_AUTHOR_EMAIL': 'p001@example.invalid',
                'GIT_COMMITTER_NAME': 'Independent P001 fixture', 'GIT_COMMITTER_EMAIL': 'p001@example.invalid',
                'PYTHONDONTWRITEBYTECODE': '1', 'GIT_ALLOW_PROTOCOL': 'file'})

    def git(folder, *argv):
        return subprocess.check_output(['git', '-C', str(folder), *argv], env=env, stderr=subprocess.PIPE).decode().strip()

    def initialize(folder):
        folder.mkdir(parents=True)
        git(folder, 'init', '-q', '-b', 'master')
        (folder / 'README.md').write_text('# Synthetic independent integration fixture\n')
        (folder / 'LICENSE').write_text('Test data generated by independent reviewer.\n')

    def commit(folder, message):
        git(folder, 'add', '.')
        git(folder, 'commit', '-qm', message)
        return git(folder, 'rev-parse', 'HEAD')

    initialize(repo)
    git(repo, 'remote', 'add', 'origin', 'https://github.com/boop-bip80/MAC-OS-EMULATION.git')
    owners = sorted({o for files in STAGES.values() for o, _ in files if o != '.'})
    folders = {'.': repo}
    for owner in owners:
        folders[owner] = sources / (Path(owner).name + '.git')
        initialize(folders[owner])
    for files in STAGES.values():
        for owner, path in files:
            target = folders[owner] / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text('/* synthetic source fixture only */\nint fixture(void) { return 0; }\n')

    nested = sources / 'nested.git'
    initialize(nested)
    nested_pin = commit(nested, 'nested leaf fixture')
    dyld = folders['src/external/dyld']
    (dyld / '.gitmodules').write_text('[submodule "nested"]\npath = deps/nested\nurl = ../nested.git\n')
    git(dyld, 'add', '.gitmodules')
    git(dyld, 'update-index', '--add', '--cacheinfo', '160000', nested_pin, 'deps/nested')
    (dyld / 'deps/nested').mkdir(parents=True)
    pins = {owner: commit(folders[owner], 'pinned child fixture') for owner in owners}
    (repo / '.gitmodules').write_text(''.join(f'[submodule "{Path(owner).name}"]\npath = {owner}\nurl = ../{Path(owner).name}.git\n' for owner in owners))
    git(repo, 'add', '.')
    for owner, pin in pins.items():
        git(repo, 'update-index', '--add', '--cacheinfo', '160000', pin, owner)
        (repo / owner).mkdir(parents=True)
    git(repo, 'commit', '-qm', 'original source fixture')

    def snapshot():
        pin = git(repo, 'rev-parse', 'HEAD')
        return {'commit': pin, 'tree': git(repo, 'rev-parse', 'HEAD^{tree}'),
                'readme': {'path': 'README.md', 'sha256': hashlib.sha256((repo / 'README.md').read_bytes()).hexdigest(),
                           'source_url': f'https://github.com/example/fixture/blob/{pin}/README.md'}}

    baseline = snapshot()
    (repo / 'README.md').write_text('# Synthetic plan fixture\n')
    commit(repo, 'plan fixture')
    integration = snapshot()

    def write(relative, data):
        target = repo / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(data, indent=2) + '\n')

    hashes = {}
    for relative, files in [('tools/compat/logic-pro', code), ('tests/compat/logic-pro/baseline', tests)]:
        target = repo / relative
        target.mkdir(parents=True, exist_ok=True)
        for name, source in files.items():
            shutil.copyfile(source, target / name)
            hashes[str(source)] = hashlib.sha256(source.read_bytes()).hexdigest()
    write('docs/compat/logic-pro/baseline.json', {'schema_version': 1, 'repository_url': 'https://github.com/example/fixture.git', 'baseline': baseline, 'integration': integration})
    write('docs/compat/logic-pro/evidence/P001/remote-snapshot.json', {
        'schema_version': 1, 'baseline_commit': baseline['commit'], 'baseline_tree': baseline['tree'],
        'integration_commit': integration['commit'], 'integration_tree': integration['tree'],
        'external_tree': {'gitlinks': [{'path': owner, 'sha': pin} for owner, pin in pins.items()]}})
    evidence = []
    for stage, files in STAGES.items():
        for owner, path in files:
            data = (folders[owner] / path).read_bytes()
            record = {'id': f'synthetic-{len(evidence)}', 'category': CATEGORIES[len(evidence) % len(CATEGORIES)],
                      'repository': owner, 'repository_commit': integration['commit'] if owner == '.' else pins[owner],
                      'gitlink_chain': [] if owner == '.' else [{'path': owner, 'commit': pins[owner]}],
                      'path': path, 'line_start': 1, 'line_end': 2, 'contains': ['synthetic source fixture only'],
                      'blob_sha1': git(folders[owner], 'rev-parse', f'HEAD:{path}'),
                      'excerpt_sha256': hashlib.sha256(data).hexdigest(),
                      'observation': 'STATIC_SOURCE_INSPECTION', 'launch_stages': [stage]}
            evidence.append(record)
    write('tools/compat/logic-pro/classifications.json', {'schema_version': 1, 'inspected_commit': integration['commit'], 'runtime_executed': False, 'evidence': evidence})
    expected = commit(repo, 'assembled P001 integration fixture')
    (work / 'tool-sha256.json').write_text(json.dumps(hashes, indent=2) + '\n')
    commands = [
        ('prepare', [sys.executable, str(repo / 'tools/compat/logic-pro/prepare_sources.py'), '--repo', str(repo), '--upstream-url', str(sources / 'project.git'), '--output', str(work / 'source-retrieval.json'), '--jobs', '2', '--allow-local-fixtures']),
        ('campaign', [sys.executable, str(repo / 'tools/compat/logic-pro/run_baseline.py'), '--repo', str(repo), '--retrieval-report', str(work / 'source-retrieval.json'), '--output-dir', str(work / 'evidence'), '--export-small-evidence']),
    ]
    outcomes = []
    for label, command in commands:
        completed = subprocess.run(command, env=env, cwd=repo, capture_output=True, timeout=180)
        (work / f'{label}.log').write_bytes(completed.stdout + completed.stderr)
        outcomes.append({'label': label, 'exit_code': completed.returncode})
    summary = json.loads((work / 'evidence/summary.json').read_text())
    result = {'workspace': str(work), 'implementation_commit': expected, 'commands': outcomes,
              'campaign_result': summary['result'], 'failures': summary['failures'],
              'fixture_tests_executed': summary['fixture_tests_executed'], 'checks': summary.get('checks'),
              'source_clean': git(repo, 'status', '--porcelain') == ''}
    (work / 'independent-result.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result, indent=2))
    return 0 if summary['result'] == 'PASS' and result['source_clean'] else 1


if __name__ == '__main__':
    sys.exit(main())
